export function seedExercise(key: string): SeedExercise | undefined {
  return SEED_EXERCISES.find((e) => e.key === key);
}

/** Merge the seed library with the user's custom exercises. */
export interface ExerciseView {
  key: string;
  name: string;
  aliases: string[];
  primary: Muscle;
  secondary: Muscle[];
  equipment: Equipment;
  pattern: Pattern;
  unilateral: boolean;
  equipmentIds: string[];
  instructions: string;
  tip: string;
  custom: boolean;
}

export function toExerciseView(e: SeedExercise): ExerciseView {
  return {
    key: e.key,
    name: e.name,
    aliases: e.aliases,
    primary: e.primary,
    secondary: e.secondary,
    equipment: e.equipment,
    pattern: e.pattern,
    unilateral: e.unilateral ?? false,
    equipmentIds: e.equipmentIds,
    instructions: e.instructions,
    tip: e.tip,
    custom: false,
  };
}
